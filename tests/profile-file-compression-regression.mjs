import assert from 'node:assert/strict';
import {gzipSync,gunzipSync} from 'node:zlib';
import {makeAccount} from '../js/workspace-model.mjs';
import {persistentAccountSnapshot} from '../js/browser-storage.mjs';
import {serializeAccountFile,parseAccountFile,serializeAccountToBiff,parseBiff,materializeImportedAccount} from '../js/biff-format.mjs';
import {serializeClanFile,parseClanFile,serializeClanProfile,parseClanProfile} from '../js/clan-profile-file.mjs';
import {readProfileText} from '../js/profile-file-compression.mjs';
const defaults={guardsman:'selected',specialist:'selected',engineer:1,monster:2};
const custom={guardsman:0,specialist:3,engineer:'selected',monster:4};
assert.deepEqual(makeAccount().exploreTierDepths,defaults);
const account=makeAccount({name:'Compression test',exploreTierDepths:custom});
account.battle.workspaces['epic-doomsday']={inputs:{leadership:12345},selectedIds:{troop:['test'],monster:[],mercenary:[]},methods:{optimize:{resultCache:{build:'test',signature:'test',payload:{result:{expectedTotalLifetimeDamage:123,diagnostics:Array.from({length:1000},(_,i)=>({index:i,damage:123456}))},quantities:{test:12}}}}}};
assert.deepEqual(persistentAccountSnapshot({main:account}).main.exploreTierDepths,custom);
assert.deepEqual(makeAccount().exploreTierDepths,defaults,'Accounts must not share preference mutations');
const options={exportedAt:'2026-11-07T00:00:00.000Z',appBuild:'test'};
const plain=serializeAccountToBiff(account,options),compressed=await serializeAccountFile(account,options);
assert.deepEqual([...new Uint8Array(await compressed.slice(0,2).arrayBuffer())],[31,139]);
assert.deepEqual(JSON.parse(gunzipSync(Buffer.from(await compressed.arrayBuffer()))),JSON.parse(plain),'Compression retains every exported field');
assert.ok(compressed.size<Buffer.byteLength(plain)/2);
for(const file of [compressed,new Blob([plain])]){
  const parsed=await parseAccountFile(file);
  assert.deepEqual(parsed,parseBiff(plain));
  const imported=materializeImportedAccount(parsed,{armyIds:['test'],optimizerCacheBuild:'test'}).account;
  assert.deepEqual(imported.exploreTierDepths,custom);
  assert.equal(imported.battle.workspaces['epic-doomsday'].methods.optimize.resultCache.payload.result.diagnostics.length,1000);
}
const legacy=JSON.parse(plain);delete legacy.account.exploreTierDepths;
assert.deepEqual((await parseAccountFile(new Blob([JSON.stringify(legacy)]))).account.exploreTierDepths,defaults);
const clan={id:'norm-test',name:'Test clan',plan:{period:'24',members:100,epics:{Doomsday:{norm:12345}},netPlayerAccountId:'local-only'}};
const clanText=serializeClanProfile(clan,options),clanFile=await serializeClanFile(clan,options);
assert.deepEqual(JSON.parse(gunzipSync(Buffer.from(await clanFile.arrayBuffer()))),JSON.parse(clanText));
for(const file of [clanFile,new Blob([clanText])])assert.deepEqual(await parseClanFile(file),parseClanProfile(clanText));
const norms=JSON.parse(clanText);norms.format='tbtoolkit-norms';norms.kind='clan-norm-profile';
assert.deepEqual(await parseClanFile(new Blob([JSON.stringify(norms)])),parseClanProfile(clanText));
assert.equal((await parseClanFile(clanFile)).plan.netPlayerAccountId,undefined);
await assert.rejects(parseAccountFile(compressed.slice(0,compressed.size-8)),/damaged or incomplete/);
await assert.rejects(parseClanFile(new Blob([new Uint8Array([31,139,0,0])])),/damaged or incomplete/);
await assert.rejects(parseAccountFile(compressed,{maxBytes:10}),/larger than/);
await assert.rejects(readProfileText(new Blob([gzipSync('x'.repeat(10000))]),{maxBytes:100,sizeLimitMessage:'Too large'}),/Too large/);
await assert.rejects(parseClanFile(new Blob([gzipSync('x'.repeat(1000001))])),/larger than 1 MB/);
console.log('Lossless compressed and legacy player/clan imports, limits, corruption, and per-account Explore preferences passed.');
